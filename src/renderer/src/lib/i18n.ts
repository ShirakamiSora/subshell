const dictionaries: Record<Language, Dict> = { zh, en };

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const template = dictionaries[language]?.[key] ?? dictionaries.zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : match,
  );
}

export function useI18n(): {
  language: Language;
  t: (key: string, vars?: Record<string, string | number>) => string;
} {
  const language = useApp((state) => state.settings?.language ?? 'zh');
  return useMemo(
    () => ({
      language,
      t: (key: string, vars?: Record<string, string | number>) => translate(language, key, vars),
    }),
    [language],
  );
}
